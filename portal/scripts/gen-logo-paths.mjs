/**
 * Turn assets/brand/logo-light.svg into src/lib/pdf/logo-paths.ts.
 * Run from portal/: node scripts/gen-logo-paths.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const svg = fs.readFileSync(path.join(root, "assets/brand/logo-light.svg"), "utf8");
const vb = svg.match(/viewBox="([\d.]+) ([\d.]+) ([\d.]+) ([\d.]+)"/);
if (!vb) throw new Error("viewBox missing");

const viewBox = {
  x: Number(vb[1]),
  y: Number(vb[2]),
  width: Number(vb[3]),
  height: Number(vb[4]),
};

function parseTransform(raw) {
  const ops = [];
  const re = /(translate|scale)\(([^)]+)\)/g;
  let m;
  while ((m = re.exec(raw))) {
    const nums = m[2].split(/[\s,]+/).map(Number);
    ops.push({ op: m[1], nums });
  }
  return ops;
}

const groupRe = /<g id="([^"]+)"([^>]*)>([\s\S]*?)<\/g>/g;
const groups = [];
let gm;
while ((gm = groupRe.exec(svg))) {
  const id = gm[1];
  const attrs = gm[2];
  const body = gm[3];
  const transform = (attrs.match(/transform="([^"]+)"/) || [])[1] || "";
  const groupFill = (attrs.match(/fill="([^"]+)"/) || [])[1] || "#1A222B";
  const shapes = [];
  const polyRe = /<polygon\b([^>]*)\/>/g;
  let pm;
  while ((pm = polyRe.exec(body))) {
    const tag = pm[1];
    const fill = (tag.match(/fill="([^"]+)"/) || [])[1] || groupFill;
    const pointsRaw = (tag.match(/points="([^"]+)"/) || [])[1] || "";
    const points = pointsRaw
      .trim()
      .split(/[\s,]+/)
      .map(Number);
    shapes.push({ kind: "polygon", fill, points });
  }
  const pathRe = /<path\b([^>]*)\/>/g;
  let dm;
  while ((dm = pathRe.exec(body))) {
    const tag = dm[1];
    const fill = (tag.match(/fill="([^"]+)"/) || [])[1] || groupFill;
    const d = ((tag.match(/d="([^"]+)"/) || [])[1] || "").replace(/\s+/g, " ").trim();
    shapes.push({ kind: "path", fill, d });
  }
  groups.push({ id, transform: parseTransform(transform), shapes });
}

const out = `/* eslint-disable */
/* Generated by scripts/gen-logo-paths.mjs from assets/brand/logo-light.svg. Do not edit. */

export type LogoOp = { op: "translate" | "scale"; nums: number[] };

export type LogoShape =
  | { kind: "polygon"; fill: string; points: number[] }
  | { kind: "path"; fill: string; d: string };

export type LogoGroup = {
  id: string;
  transform: LogoOp[];
  shapes: LogoShape[];
};

export const LOGO_VIEWBOX = ${JSON.stringify(viewBox, null, 2)} as const;

export const LOGO_GROUPS: LogoGroup[] = ${JSON.stringify(groups, null, 2)};
`;

const dest = path.join(root, "src/lib/pdf/logo-paths.ts");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log("wrote", dest, "groups", groups.map((g) => `${g.id}:${g.shapes.length}`).join(", "));
